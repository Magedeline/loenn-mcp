"""Regenerate the tool reference in README.md from the live server registry.

    python tools/gen_tool_reference.py          # rewrite the block between the markers
    python tools/gen_tool_reference.py --check  # exit 1 if the README is out of date

Tools are grouped by the "#  SECTION" banner above them in server.py.
"""

import asyncio
import inspect
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.environ["LOENN_MCP_TOOLS"] = "all"

from loenn_mcp import server  # noqa: E402

START, END = "<!-- tools:start -->", "<!-- tools:end -->"


def sections() -> list[tuple[int, str]]:
    src = (ROOT / "loenn_mcp" / "server.py").read_text(encoding="utf-8").splitlines()
    out = []
    for i, line in enumerate(src, 1):
        m = re.match(r"^#  ([A-ZÖ][^\n]*)$", line)
        if m and i > 1 and src[i - 2].startswith("# ═"):
            out.append((i, m.group(1).strip().split(" — ")[0].split(" (")[0].title().replace("Lönn", "Lönn")))
    return out


def build() -> str:
    secs = sections()
    tools = asyncio.run(server.mcp.list_tools())
    groups: dict[str, list[tuple[int, str, str]]] = {}
    for t in tools:
        fn = getattr(server, t.name, None)
        line = inspect.getsourcelines(inspect.unwrap(fn))[1] if fn else 0
        title = next((name for start, name in reversed(secs) if start <= line), "Other")
        desc = (t.description or "").split("\n\n")[0]
        groups.setdefault(title, []).append((line, t.name, desc))
    order = sorted(groups, key=lambda g: min(l for l, _, _ in groups[g]))
    hidden = server._EXTRA_TOOLS
    n_all = len(tools)
    lines = [START, "",
             f"{n_all} tools; {n_all - len(hidden & {t.name for t in tools})} are listed by default. "
             "Tools marked *extra* are hidden unless `LOENN_MCP_TOOLS=all`. "
             "Generated by `tools/gen_tool_reference.py`.", ""]
    for g in order:
        lines += [f"#### {g}", "", "| Tool | What it does |", "|---|---|"]
        for _, name, desc in sorted(groups[g]):
            mark = " *(extra)*" if name in hidden else ""
            lines.append(f"| `{name}`{mark} | {desc.replace('|', '/')} |")
        lines.append("")
    lines.append(END)
    return "\n".join(lines)


def main() -> int:
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    block = build()
    if START in text:
        new = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    else:
        raise SystemExit(f"README has no {START} marker")
    if "--check" in sys.argv:
        return 0 if new == text else 1
    readme.write_text(new, encoding="utf-8")
    print(f"README tool reference updated ({block.count('| `')} tools)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
